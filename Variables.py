# String Variable
name = "Nasreen Shah"
print(name)

# Integer Variable
age = 25
print(age)

# Float Variable
height = 5.4
print(height)

# Boolean Variable
is_student = True
print(is_student)

# Numeric Value
num = 38
print(num)

# Multiple Variables
first_name = "Nasreen"
last_name = "Shah"
print(first_name, last_name)

# Simple Calculation
a = 10
b = 20
sum = a + b
print(sum)